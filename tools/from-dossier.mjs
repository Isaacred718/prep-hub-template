#!/usr/bin/env node
/* from-dossier.mjs — scaffold a complete study app from a research dossier.

   Usage:
     node tools/from-dossier.mjs <dossier.json> <target-folder> [--force]

   The dossier is the research stage's output (pipeline/RESEARCH.md),
   valid against schemas/dossier.schema.json. This tool is deliberately
   deterministic — no AI runs here. It copies the engine files unchanged,
   generates topic.js from the dossier (tracks, exam, duties, library,
   roadmap, copy), writes empty-but-valid data/ files for the build stage
   to fill, and drops a data/docs/SOURCES.md checklist of the library
   files to fetch. See pipeline/BUILD.md for what happens next.

   No dependencies; Node 16+. */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const ENGINE = ['index.html', 'styles.css', 'settings.js', 'app.js', 'forge.js', 'auth.js', 'sw.js'];
const FORCE = process.argv.includes('--force');
const args = process.argv.slice(2).filter(a => a !== '--force');
const [dossierPath, targetArg] = args;

function fail(msg) { console.error('from-dossier: ' + msg); process.exit(1); }
if (!dossierPath || !targetArg) fail('usage: node tools/from-dossier.mjs <dossier.json> <target-folder> [--force]');
if (!fs.existsSync(dossierPath)) fail('dossier not found: ' + dossierPath);

let D;
try { D = JSON.parse(fs.readFileSync(dossierPath, 'utf8')); }
catch (e) { fail('dossier is not valid JSON: ' + e.message); }

/* ---------- minimal contract check (full check: schemas/dossier.schema.json) ---------- */
for (const k of ['topic', 'tracks', 'domains', 'sources'])
  if (!D[k]) fail('dossier is missing required section: ' + k);
for (const k of ['id', 'name', 'title'])
  if (!D.topic[k]) fail('dossier topic is missing: ' + k);
if (!/^[a-z0-9-]+$/.test(D.topic.id)) fail('topic.id must be a lowercase slug (a-z, 0-9, hyphens)');
if (!D.tracks.length) fail('dossier tracks is empty');
const trackIds = new Set(D.tracks.map(t => t.id));
for (const t of D.tracks) {
  if (t.prerequisite && !trackIds.has(t.prerequisite))
    fail('track ' + t.id + ' has unknown prerequisite: ' + t.prerequisite);
}
if (D.duties) for (const [track, d] of Object.entries(D.duties)) {
  if (!trackIds.has(track) && track !== 'ANP') fail('duties reference unknown track: ' + track);
  const sum = Object.values(d.weights || {}).reduce((a, b) => a + b, 0);
  if (Math.abs(sum - 100) > 0.5)
    console.warn('from-dossier: warning — duty weights for ' + track + ' sum to ' + sum + ', not 100 (kept as researched; see dossier researchNotes)');
}

const target = path.resolve(targetArg);
if (fs.existsSync(target) && fs.readdirSync(target).length && !FORCE)
  fail('target folder is not empty: ' + target + ' (use --force to write anyway)');
fs.mkdirSync(path.join(target, 'data', 'docs'), { recursive: true });

/* ---------- engine, unchanged ---------- */
for (const f of ENGINE) fs.copyFileSync(path.join(ROOT, f), path.join(target, f));
fs.mkdirSync(path.join(target, 'tools'), { recursive: true });
fs.copyFileSync(path.join(ROOT, 'tools', 'validate.mjs'), path.join(target, 'tools', 'validate.mjs'));

/* ---------- topic.js, generated from the dossier ---------- */
const q = s => JSON.stringify(s);
const exam = D.exam || {};
const lengths = (exam.lengths && exam.lengths.length) ? exam.lengths
  : [{ n: 25, label: 'Quick' }, { n: 50, label: 'Standard', default: true }];
const blurb = (D.topic.blurb) ||
  ('Master ' + D.topic.name + ' with {questions} practice questions, {cards} flashcards, ' +
   '{guides} study guides and {drills} scenario drills — every question explained.');

let topic = `/* topic.js — everything that makes this app about ${D.topic.name} lives here.
   GENERATED by tools/from-dossier.mjs from the research dossier
   (${path.basename(dossierPath)}). The engine files are topic-agnostic;
   regenerate by re-running the tool, or hand-edit — this file is the app.
   Written as a plain \`var\` so the service worker can importScripts() it. */
var TOPIC = {
  id: ${q(D.topic.id)},
  name: ${q(D.topic.name)},
  title: ${q(D.topic.title)},
  version: '1.0',
  accent: ${q(D.topic.accent || 'sky')},
  iconText: ${q(D.topic.iconText || D.topic.name.replace(/[^A-Za-z]/g, '').slice(0, 3).toUpperCase() || 'ST')},

  trackLabel: ${q(D.topic.trackLabel || 'Certification')},
  tracks: ${JSON.stringify(D.tracks.map(t => ({ id: t.id, label: t.label })), null, 2).replace(/\n/g, '\n  ')},
  defaultTrack: ${q(D.tracks[0].id)},

  exam: {
    passMark: ${exam.passMark ?? 70},
    lengths: ${JSON.stringify(lengths, null, 2).replace(/\n/g, '\n    ')},
    simQuestions: ${exam.simQuestions ?? 100},
    simMinutes: ${exam.simMinutes ?? 120},
    disclaimer: ${q(exam.disclaimer || 'Treat this as a practice benchmark, not an official score.')}
  },

  advancedPrefix: ${q(D.topic.advancedPrefix || '')},

  copy: {
    blurb: ${q(blurb)},
    careersIntro: 'Ranked by your readiness in the domains each role leans on.',
    drillsIntro: 'Short scenarios that end in a decision, not isolated facts.'
  },
  careers: [],

  levels: ['Foundations', 'Core Knowledge', 'Proficient', 'Advanced', 'Expert'],
  difficulty: {
    hard: 'calculat|scenario|troubleshoot|best practice|most likely|except|difference between|compare|sequence|how many|how much',
    easy: '^(what is|what are|what does|which of the following is the term)'
  },
  rephrasePrefixes: ['Quick check: ', 'Think it through: ', 'In practice: ', 'One more time: '],
`;

if (D.duties) {
  topic += `
  // Official blueprint per track (dossier): duty weights in percent.
  duties: ${JSON.stringify(D.duties, null, 2).replace(/\n/g, '\n  ')},
`;
}
if (D.library) {
  topic += `
  // Document Library tab (dossier sources with a localFile).
  library: ${JSON.stringify(D.library, null, 2).replace(/\n/g, '\n  ')},
`;
}
if (D.roadmap) {
  topic += `
  // Roadmap tab: one checklist per track, in order.
  roadmap: ${JSON.stringify(D.roadmap, null, 2).replace(/\n/g, '\n  ')},
`;
}
topic += `
  // Google sign-in + cloud sync. null = this device only. To enable, copy
  // the sync block from the CTS Prep topic.js and change the collection
  // to "<topic id>_users".
  sync: null
};
`;
fs.writeFileSync(path.join(target, 'topic.js'), topic);

/* ---------- data stubs for the build stage ---------- */
const domainsNote = D.domains.map(d => '//   - ' + d.name + (d.duty ? ' (duty ' + d.duty + ')' : '')).join('\n');
fs.writeFileSync(path.join(target, 'data', 'questions.js'),
`// Question bank. Contract: schemas/questions.schema.json.
// Domains (use verbatim — readiness groups by these):
${domainsNote}
// Tracks: ${[...trackIds].join(', ')}. Targets: ${JSON.stringify((D.contentTargets || {}).questionsPerTrack || {})}
const QUESTIONS = [
];
`);
fs.writeFileSync(path.join(target, 'data', 'cards.js'),
`// Flashcards (Leitner spaced repetition). Contract: schemas/cards.schema.json.
// domain + front must be unique. Target per domain: ${(D.contentTargets || {}).cardsPerDomain ?? '—'}
const CARDS = [
];
`);
fs.writeFileSync(path.join(target, 'data', 'guides.js'),
`// Study guides. Contract: schemas/guides.schema.json.
// body is light markdown (## ### - 1. **bold** *italic* \`code\`).
const GUIDES = [
  {
    "title": "How to use this app",
    "domain": ${q(D.domains[0].name)},
    "body": "Work the loop: read a guide, drill the flashcards until they feel easy, then take a practice test and read every explanation — especially for the questions you got right by guessing.\\n\\n## The tabs\\n\\n- **Guides** — the reading. Start here for a new domain.\\n- **Cards** — spaced repetition; cards you miss come back sooner.\\n- **Quiz** — quick untimed checks by domain.\\n- **Practice** — generated tests with a timer and a full breakdown.\\n- **Drills** — short scenarios that end in a decision.\\n- **Endless** — an adaptive stream that levels up as you improve.\\n\\nYour progress is saved on this device and feeds the readiness scores on the home page."
  }
];
`);
fs.writeFileSync(path.join(target, 'data', 'drills.js'),
`// Scenario drills. Contract: schemas/drills.schema.json.
// Target count: ${(D.contentTargets || {}).drills ?? '—'}
const DRILLS = [
];
`);
fs.writeFileSync(path.join(target, 'data', 'forge.js'),
`// Question forge (Endless-mode generators). Optional — an empty body means
// Endless draws from the question bank only. See TEMPLATE.md section on
// the forge for F.calc / F.concepts / F.tricks.
(function (F) {
})(FORGE);
`);

/* ---------- sources checklist ---------- */
const srcLines = D.sources.map(s => {
  const box = s.localFile ? '[ ]' : '[x]';
  return `- ${box} **${s.title}** (${s.kind}${s.track ? ', ' + s.track : ''}${s.gated ? ', GATED' : ''})` +
    (s.localFile ? `\n  → save as \`data/docs/${s.localFile}\`` : '') +
    (s.url ? `\n  ${s.url}` : '') +
    (s.description ? `\n  ${s.description}` : '');
}).join('\n');
fs.writeFileSync(path.join(target, 'data', 'docs', 'SOURCES.md'),
`# Library sources for ${D.topic.name}

Fetch each file below into this folder under the exact name given, and
verify it is the genuine document (PDF header, sensible size). Gated
sources are skipped — never pull them from unofficial mirrors.

${srcLines}
`);

console.log('from-dossier: app scaffolded at ' + target);
console.log('  topic.js: ' + D.tracks.length + ' track(s)' +
  (D.duties ? ', duties for ' + Object.keys(D.duties).join('/') : '') +
  (D.library ? ', library with ' + D.library.groups.reduce((n, g) => n + g.docs.length, 0) + ' doc(s)' : '') +
  (D.roadmap ? ', roadmap with ' + D.roadmap.tracks.length + ' checklist(s)' : ''));
console.log('  next: fetch data/docs (see data/docs/SOURCES.md), write content to the');
console.log('  dossier targets, then run: node tools/validate.mjs ' + target + ' --strict');
